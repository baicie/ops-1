#!/usr/bin/env bash
# Prepare a strict SSH context for the staging deploy job (runs on the GitHub runner).
#
# Writes:
#   ~/.ssh/id_deploy                  deploy private key, 0600, never echoed
#   ~/.ssh/opsweave_known_hosts       the pinned host key, 0600
#   ~/.ssh/opsweave_staging_config    ssh_config for the alias "opsweave-staging"
#
# Exports for later steps (via $GITHUB_ENV when available):
#   SSH_CONFIG_FILE, SSH_HOST_ALIAS, SSH_KNOWN_HOSTS_FILE
#
# Host verification is enforced by UserKnownHostsFile + StrictHostKeyChecking yes. There is no
# path through this script that accepts an unknown host key: a mismatch aborts the job.

set -euo pipefail

SSH_DIR="${HOME}/.ssh"
KEY_PATH="$SSH_DIR/id_deploy"
KNOWN_HOSTS_PATH="$SSH_DIR/opsweave_known_hosts"
CONFIG_PATH="$SSH_DIR/opsweave_staging_config"
HOST_ALIAS="opsweave-staging"
KEY_TYPE_RE='^(ssh-ed25519|ssh-rsa|ssh-dss|rsa-sha2-256|rsa-sha2-512|ecdsa-sha2-[a-z0-9-]+|sk-[a-z0-9@.-]+)$'

fail() {
  printf 'ci-ssh-setup: ERROR %s\n' "$*" >&2
  exit 1
}

note() {
  printf 'ci-ssh-setup: %s\n' "$*" >&2
}

require_env() {
  local name="$1" value
  value="${!name:-}"
  if [ -z "${value//[[:space:]]/}" ]; then
    fail "required environment variable $name is empty; configure it as a secret on the 'staging' GitHub Environment"
  fi
}

for required in STAGING_HOST STAGING_USER STAGING_SSH_KEY STAGING_HOST_KEY; do
  require_env "$required"
done

STAGING_PORT="${STAGING_PORT:-22}"
if ! printf '%s' "$STAGING_PORT" | grep -Eq '^[0-9]{1,5}$'; then
  fail "STAGING_PORT must be numeric, got '$STAGING_PORT'"
fi

HOST_KEY_NAME="$STAGING_HOST"
if [ "$STAGING_PORT" != "22" ]; then
  HOST_KEY_NAME="[$STAGING_HOST]:$STAGING_PORT"
fi

umask 077
mkdir -p "$SSH_DIR"
chmod 700 "$SSH_DIR"

# Private key: written from the environment, validated, and reported only by fingerprint.
printf '%s\n' "$STAGING_SSH_KEY" | tr -d '\r' >"$KEY_PATH"
chmod 600 "$KEY_PATH"
if ! ssh-keygen -y -f "$KEY_PATH" >/dev/null 2>&1; then
  rm -f "$KEY_PATH"
  fail "STAGING_SSH_KEY is not a usable unencrypted OpenSSH private key"
fi
KEY_FINGERPRINT="$(ssh-keygen -y -f "$KEY_PATH" | ssh-keygen -lf - | awk '{print $2}')"

# Host key: accept either a bare "type base64" pair or a full known_hosts line, then bind the key
# material to the host we are actually connecting to.
TMP_KNOWN="$KNOWN_HOSTS_PATH.tmp"
: >"$TMP_KNOWN"
chmod 600 "$TMP_KNOWN"
entries=0
while IFS= read -r line; do
  line="${line%$'\r'}"
  line="${line#"${line%%[![:space:]]*}"}"
  line="${line%"${line##*[![:space:]]}"}"
  [ -n "$line" ] || continue
  case "$line" in
    '#') continue ;;
    '#'*) continue ;;
  esac
  if [ "${line:0:1}" = "|" ]; then
    printf '%s\n' "$line" >>"$TMP_KNOWN"
    entries="$((entries + 1))"
    continue
  fi
  read -r first second third rest <<<"$line"
  if printf '%s' "${first:-}" | grep -Eq "$KEY_TYPE_RE"; then
    key_type="${first:-}"
    key_blob="${second:-}"
    written_host=""
  else
    written_host="${first:-}"
    key_type="${second:-}"
    key_blob="${third:-}"
  fi
  if [ -z "${key_type:-}" ] || [ -z "${key_blob:-}" ]; then
    rm -f "$TMP_KNOWN"
    fail "STAGING_HOST_KEY contains a line that is neither a bare public key nor a known_hosts entry"
  fi
  if ! printf '%s' "$key_type" | grep -Eq "$KEY_TYPE_RE"; then
    rm -f "$TMP_KNOWN"
    fail "STAGING_HOST_KEY uses an unsupported key type '$key_type'"
  fi
  if [ -n "$written_host" ] && [ "$written_host" != "$HOST_KEY_NAME" ]; then
    note "STAGING_HOST_KEY was labelled '$written_host'; rebinding the same key to $HOST_KEY_NAME"
  fi
  printf '%s %s %s\n' "$HOST_KEY_NAME" "$key_type" "$key_blob" >>"$TMP_KNOWN"
  entries="$((entries + 1))"
done <<<"$STAGING_HOST_KEY"

if [ "$entries" -eq 0 ]; then
  rm -f "$TMP_KNOWN"
  fail "STAGING_HOST_KEY contained no usable host key; expected the output of 'ssh-keyscan -p <port> <host>'"
fi
if ! ssh-keygen -lf "$TMP_KNOWN" >/dev/null 2>&1; then
  rm -f "$TMP_KNOWN"
  fail "STAGING_HOST_KEY does not parse as an OpenSSH host key"
fi
mv -f "$TMP_KNOWN" "$KNOWN_HOSTS_PATH"
chmod 600 "$KNOWN_HOSTS_PATH"
HOST_KEY_FINGERPRINTS="$(ssh-keygen -lf "$KNOWN_HOSTS_PATH" | awk '{print $2}' | paste -sd, -)"

cat >"$CONFIG_PATH" <<EOF
# Generated by scripts/ci-ssh-setup.sh for one CI run.
Host $HOST_ALIAS
  HostName $STAGING_HOST
  User $STAGING_USER
  Port $STAGING_PORT
  IdentityFile $KEY_PATH
  IdentitiesOnly yes
  UserKnownHostsFile $KNOWN_HOSTS_PATH
  GlobalKnownHostsFile /dev/null
  StrictHostKeyChecking yes
  CheckHostIP no
  BatchMode yes
  ConnectTimeout 20
  ServerAliveInterval 15
  ServerAliveCountMax 4
  ForwardAgent no
  RequestTTY no
EOF
chmod 600 "$CONFIG_PATH"

if ! ssh -F "$CONFIG_PATH" -G "$HOST_ALIAS" >/dev/null 2>&1; then
  fail "generated ssh_config does not resolve; refusing to continue"
fi

export SSH_CONFIG_FILE="$CONFIG_PATH"
export SSH_HOST_ALIAS="$HOST_ALIAS"
export SSH_KNOWN_HOSTS_FILE="$KNOWN_HOSTS_PATH"

if [ -n "${GITHUB_ENV:-}" ]; then
  {
    printf 'SSH_CONFIG_FILE=%s\n' "$CONFIG_PATH"
    printf 'SSH_HOST_ALIAS=%s\n' "$HOST_ALIAS"
    printf 'SSH_KNOWN_HOSTS_FILE=%s\n' "$KNOWN_HOSTS_PATH"
  } >>"$GITHUB_ENV"
fi

note "host alias '${HOST_ALIAS}' -> $STAGING_USER@$STAGING_HOST:$STAGING_PORT"
note "deploy key fingerprint: $KEY_FINGERPRINT"
note "pinned host key fingerprint(s): $HOST_KEY_FINGERPRINTS"
note "host verification is enforced against $KNOWN_HOSTS_PATH; later steps must use 'ssh -F $CONFIG_PATH $HOST_ALIAS'"
